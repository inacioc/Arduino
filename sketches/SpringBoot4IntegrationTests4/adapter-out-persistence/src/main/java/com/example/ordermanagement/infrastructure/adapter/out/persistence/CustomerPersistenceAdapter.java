package com.example.ordermanagement.infrastructure.adapter.out.persistence;

import com.example.ordermanagement.domain.exception.CustomerAlreadyExistsException;
import com.example.ordermanagement.domain.model.Customer;
import com.example.ordermanagement.domain.port.out.CustomerRepositoryPort;
import org.springframework.stereotype.Component;

import java.util.List;
import java.util.Optional;
import java.util.UUID;

@Component
public class CustomerPersistenceAdapter extends AbstractPersistenceAdapter implements CustomerRepositoryPort {

    private final CustomerJpaRepository jpaRepository;
    private final CustomerEntityMapper mapper;

    public CustomerPersistenceAdapter(CustomerJpaRepository jpaRepository, CustomerEntityMapper mapper) {
        super("Customer");
        this.jpaRepository = jpaRepository;
        this.mapper        = mapper;
    }

    @Override
    public Customer save(Customer customer) {
        // Customer.id is server-generated by Customer.create() - never an upsert key the way
        // Product.id is (see ProductPersistenceAdapter) - so save() is a genuine, one-shot
        // insert and saveAndFlush is needed for the same reason it is there: force the
        // INSERT (and its unique-constraint check on email) to happen inside this try/catch,
        // not deferred to commit.
        return executeAndTranslate(
                () -> mapper.toDomain(jpaRepository.saveAndFlush(mapper.toEntity(customer))),
                customer.getEmail(),
                (entityName, email) -> new CustomerAlreadyExistsException(email));
    }

    @Override
    public Optional<Customer> findById(UUID id) {
        return executeAndTranslate(
                () -> jpaRepository.findById(id).map(mapper::toDomain),
                id.toString());
    }

    @Override
    public Optional<Customer> findByEmail(String email) {
        return executeAndTranslate(
                () -> jpaRepository.findByEmail(email).map(mapper::toDomain),
                email);
    }

    @Override
    public List<Customer> findAll() {
        return executeAndTranslate(
                () -> jpaRepository.findAll().stream().map(mapper::toDomain).toList(),
                "all");
    }

    @Override
    public void deleteById(UUID id) {
        executeAndTranslate(() -> {
            jpaRepository.deleteById(id);
            return null;
        }, id.toString());
    }
}
